#include "ft_printf.h"

int	ft_putstr_len(char *str)
{
	int	i;

	if (!str)
		return (ft_putstr_len("(null)"));
	i = 0;
	while (str[i])
	{
		write(1, &str[i], 1);
		i++;
	}
	return (i);
}
